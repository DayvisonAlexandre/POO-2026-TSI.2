# Solicita dois valores inteiros
A = int(input("Digite o valor de A: "))
B = int(input("Digite o valor de B: "))

# Exibe os resultados
print("A + B =", A + B)
print("A * B =", A * B)
print("A - B =", A - B)

# Verifica se B é diferente de zero antes da divisão
if B != 0:
    print("A / B =", A / B)
else:
    print("A / B = Não é possível dividir por zero")

